/** Format a snap7 error code as hexadecimal value together with its name */
export function formatError(code: number): string {
    return `0x${(code >>> 0).toString(16)}${errorCodes[code] ? ` (${errorCodes[code]})` : ''}`;
}

/** Format a socket error code together with its name */
export function formatSysError(code: number): string {
    return `${code}${sysErrors[code] ? ` (${sysErrors[code]})` : ''}`;
}
